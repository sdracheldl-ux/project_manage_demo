def td(text=None, rowspan=1, ul=False, items=None, rd=False):
    attr=''
    if rowspan>1:
        attr=f' rowspan="{rowspan}"'
    if ul:
        lis=''.join(f'<li>{esc(x)}</li>' for x in items)
        return f'<td vertical-align="top"{attr}><ul>{lis}</ul></td>'
    return f'<td vertical-align="top"{attr}><p>{esc(text)}</p></td>'

