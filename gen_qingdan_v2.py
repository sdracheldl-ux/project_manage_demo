# 简化：分别计算两个列的 rowspan（0列按module连续；1列按(module,l1)连续）
def calc(idx):
    spans={}  # start_index -> count
    i=0
    n=len(exp)
    while i<n:
        j=i
        while j<n and exp[j][idx]==exp[i][idx] and (idx==0 or exp[j][0]==exp[i][0]):
            j+=1
        if j-i>1:
            spans[i]=j-i
        i=j
    return spans

