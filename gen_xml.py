# 计算每个值的 rowspan（连续相同的值合并）
modules, level1s = [], []
prev = None
for r in rows:
    if r[0] != prev:
        modules.append({"value": r[0], "start": len(modules) and None, "count": 1, "first": True})
        prev = r[0]
        modules[-1]["start_idx"] = rows.index  # placeholder
    else:
        modules[-1]["count"] += 1

# 重新计算，带起始索引
modules.clear()
for i, r in enumerate(rows):
    if i == 0 or r[0] != rows[i-1][0]:
        modules.append({"value": r[0], "start": i, "count": 1})
    else:
        modules[-1]["count"] += 1

level1s.clear()
for i, r in enumerate(rows):
    if i == 0 or (r[1] != rows[i-1][1] or r[0] != rows[i-1][0]):
        level1s.append({"value": r[1], "start": i, "count": 1})
    else:
        level1s[-1]["count"] += 1

def td(text, rowspan=None):
    rs = f' rowspan="{rowspan}"' if rowspan and rowspan > 1 else ""
    return f'<td vertical-align="top"{rs}><p>{text}</p></td>'

def td_ul(items):
    lis = "".join(f"<li>{it}</li>" for it in items)
    return f'<td vertical-align="top"><ul>{lis}</ul></td>'

body = []
for i, (m, l1, l2, points) in enumerate(rows):
    cells = []
    # 功能模块列：仅分组合起始行输出，被合并行不写
    mg = next((x for x in modules if x["start"] == i), None)
    if mg:
        cells.append(td(m, mg["count"]))
    # 一级功能项列：仅分组合起始行输出，被合并行不写
    lg = next((x for x in level1s if x["start"] == i), None)
    if lg:
        cells.append(td(l1, lg["count"]))
    # 二级功能项、功能点、RD Check
    cells.append(td(l2))
    cells.append(td_ul(points))
    cells.append(td("✅"))
    body.append("<tr>" + "".join(cells) + "</tr>")

xml = f'''# 项目全周期管理平台功能清单

<table>
<colgroup><col/><col/><col/><col/><col/></colgroup>
<thead><tr><th><p>功能模块</p></th><th><p>一级功能项</p></th><th><p>二级功能项</p></th><th><p>功能点说明</p></th><th><p>RD Check</p></th></tr></thead>
<tbody>
{chr(10).join(body)}
</tbody>
</table>
'''

with open("功能清单-合并.xml", "w", encoding="utf-8") as f:
    f.write(xml)

print(f"生成完成：{len(rows)} 行，{len(modules)} 个模块分组，{len(level1s)} 个一级功能分组")
